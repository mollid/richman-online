/**
 * Golden 回归基线：确定性 bot 对跑的逐帧状态散列序列。
 *
 * 这是本轮技术债重构期间**唯一能证明「行为不变」**的手段 —— 四百多个单测各自只断言
 * 局部规则，重构时可能全绿却已经改变整局演化；本测试把整局的状态轨迹压成散列序列，
 * 任何一处规则、抽数顺序或金额取整的差异都会在这里暴露。
 *
 * 使用纪律：
 * - 纯重构波（拆 handler、switch 改注册表、效果逻辑搬回各系统模块）⇒ 散列必须逐位不变。
 * - 功能波（神明上棋盘、结束条件、角色特技）会**合法地**改变散列 ⇒ 更新本文件基线，
 *   并在 commit message 里写明改动原因。
 *
 * 基线参数：seed=20260105、startDate=2026-01-05（周一）、`maxTurns=600`，
 * 神明现身机制**开启**（`spawnGods` 默认值，与线上新开的一局同口径）。
 * 600 只是保险上限：两局都在此之前**自然收束**（两人局 turn=126、四人局 turn=588 抵达
 * `game_over`），所以基线覆盖的是完整一局，包含倒闭清算、拍卖、认输这些只在尾声出现的分支。
 *
 * 重录历史（每次都写明原因，便于把「规则真的变了」和「只是基线过期」区分开）：
 * - R3-a：`GameState` 新增 `turnStage` 字段（回合内子阶段，CORE-02）。该字段不参与任何规则
 *   判定，重录前后 `steps` / `stalls` / `errors` 与每个采样点的 `#步数@回合` 序号完全一致，
 *   只有散列值变化 —— 纯形状变化、零行为漂移；由 `.scratch/diffcheck.sh` 的新旧引擎差分
 *   （24 局 12456 个动作，剔除新增键后逐帧全等）佐证。
 * - R3-d：bot 的炒股决策改用存款并向注册表确认数量（旧实现按现金推测，每回被引擎拒绝后
 *   落到兜底 END_TURN）。这是**决策变化而非规则变化**，因此前 10 个采样点逐字相同、
 *   自第 110 步起分叉；代价是被吞错误 6 → 0，两人局的轨迹也从 20 个采样点延长到 24 个。
 * - W1：取消自定的「商业地购地价 = 标价 ×1.5」，回到 help[22] 的公定地价。这是**规则变化**
 *   （买地金额与随后的资金流都不同），四人局从第 110 步、两人局从第 90 步起分叉；
 *   两人局的动作数由 249 变为 238。基线由 `.scratch/record-golden.sh` 重录。
 * - W2：神明改为日切随机现身、驻留棋盘格、经过即附身（`GameState.boardGods`）。这是**规则
 *   变化 + 新增一条日切随机源**，整局从第 10 步起就分叉，无一采样点相同；动作数四人局
 *   217→232、两人局 238→283（附身结束回合、被附身者又多走几位）。被吞错误仍为 0 ——
 *   新增的「请神卡无神可请」这类棋盘前提都走 `CardDef.guard`，门控与引擎同源。
 *   同波顺手修掉记忆翻牌活锁（bot 原先一律猜 0-2 号杯，而该小游戏是 8 张牌，翻过的牌被
 *   引擎拒绝 ⇒ 一局 2216 个被吞错误、整局卡在 `awaiting_pick`）。
 * - W3：拍卖收口规则改了（最小加价 1 元 → `max(¥50, 当前价 ×10%)`；PASS 与 GIVE UP 分成
 *   两个动作；收锤不再要求最高价者本人也放弃一次）。这两局在 141 回合窗口内**没有触发拍卖**，
 *   所以散列逐位不变 —— 基线的变化来自下一条：窗口从 141 放大到 300 之后，两人局照常
 *   在 turn=137 收束（轨迹不变），四人局则从「被窗口截断」变成跑到 turn=259 自然分出胜负，
 *   多出 200 个动作与 24 个采样点。换句话说：这一条**不是行为漂移，而是覆盖面变大**。
 *   曾经把 `maxTurns` 限制在 141 的两个活锁（记忆翻牌、拍卖会）都已在 W2 / W3 修掉，
 *   窗口因此放开。若将来再出现「烧完 maxTurns×12 个动作仍不收口」的局面，`stalls` 会先报错。
 * - W3 后续（拆老录像兼容层）：`GameState` 把「神明现身是否开启」从 `boardGods === null`
 *   这个双重语义里拆出来，独立成 `spawnGods` 布尔位（开发阶段不为老录像做保底）。
 *   该字段不参与任何规则判定，重录前后 `steps`（479 / 283）、`stalls`、`errors` 与每个
 *   采样点的 `#步数@回合` 序号逐字相同，只有散列值变化 —— 又一次纯形状变化、零行为漂移。
 * - W4（天数上限）：`GameState` 再加 `maxDays` 与 `endReason`。golden 两局按默认跑
 *   （`maxDays = null` ⇒ 不限天数），新增的日切钩子在整个轨迹里一次都没触发，因此同样是
 *   `steps` 逐字相同、只有散列变化的纯形状漂移。真正带上限收场那条路径由
 *   `game_end.test.ts` 直接钉，不靠 golden 覆盖。
 * - W4 后续（神明「同对不共现」补漏）：W2 只把这条不变式加在**日切现身**一个入口上，
 *   神庙摇籤仍是全池随机 —— 于是两个人可以先后摇到同一尊（实测截图：两家同时挂
 *   「小福神·7天」）。现在候选池按「棋盘驻留 + 已附身」的配对键筛（`presentGodPairKeys`），
 *   诸神皆有主时摇籤落空、只播报「无应验」。这是**规则变化**：附身对象变了、资金流跟着变，
 *   两人局从第 10 步起分叉（283→222 步、turn 137→126），四人局 479→1013 步并打到
 *   turn=588 才真正分出胜负 —— 所以窗口从 300 放到 600，否则基线又退化成「被窗口截断的
 *   一局」。回归守卫是 `gods_board.test.ts` 里的属性测试：三个 seed 的整局轨迹每一帧都
 *   断言「同对不共现」。
 */

